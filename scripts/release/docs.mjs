export function generatedPages(src) {
  const cli = parseHelp(src.help)
    .map((c) => [`## agent-kit ${c.cmd}`, "", `${cap(c.summary)}.`, "", "```bash", c.usage, ...c.details.map((d) => `    ${d}`), "```"].join("\n"))
    .join("\n\n")
  const choices = (key) => (src.questions[key] ?? []).map((o) => `\`${o.value}\`${o.hint ? ` — ${o.hint}` : ` — ${o.label}`}`).join("<br>")
  const config = [
    "| Field | What | Default |",
    "|---|---|---|",
    ...CONFIG_FIELDS.map(([f, what, def]) => `| \`${f}\` | ${what}${src.questions[f] ? `<br>${choices(f)}` : ""} | ${def} |`),
  ].join("\n")
  const skills = src.skills
    .map((s) =>
      [
        `## ${s.name}`,
        "",
        s.description,
        "",
        `- **Origin**: ${s.origin === "plugin" ? "plugin (every project)" : "template (installed in `.claude/skills/` of projects on that stack)"}`,
        ...(s.files.length ? [`- **Files**: ${s.files.map((f) => `\`${f}\``).join(", ")}`] : []),
      ].join("\n"),
    )
    .join("\n\n")
  const hooks = [
    "| Event | Matcher | Script | What it does |",
    "|---|---|---|---|",
    ...src.hooks.map((h) => `| \`${h.event}\` | ${h.matcher ? `\`${h.matcher}\`` : "—"} | \`${h.script}\` | ${h.summary} |`),
  ].join("\n")
  const scripts = src.scripts
    .map((s) => [`## ${s.name}`, "", s.summary, ...(s.usage.length ? ["", "```bash", ...s.usage, "```"] : [])].join("\n"))
    .join("\n\n")
  const changelog = src.changelog.replace(/^# Changelog\s*\n/, "")
  return {
    [`${REF}/1.cli.md`]: page("CLI", "Every agent-kit command and flag.", "i-lucide-terminal", `${NOTICE("cli/lib/help.mjs")}\n\nRun with \`npx @razcue/agent-kit <command>\`.\n\n${cli}`),
    [`${REF}/2.configuration.md`]: page("Configuration", "Every field of agent-kit.json.", "i-lucide-settings", `${NOTICE("cli/lib/init.mjs")}\n\n\`agent-kit.json\` holds the setup answers. Change them by re-running \`agent-kit init\`.\n\n${config}`),
    [`${REF}/3.skills.md`]: page("Skills", "Every skill and when it loads.", "i-lucide-sparkles", `${NOTICE("plugin/skills and templates/skills")}\n\nOnly the description of each skill loads every session; the body loads when a task needs it.\n\n${skills}`),
    [`${REF}/4.hooks.md`]: page("Hooks", "The plugin hooks and what they enforce.", "i-lucide-webhook", `${NOTICE("plugin/hooks/hooks.json")}\n\nHooks are silent outside agent-kit projects and never block on their own errors.\n\n${hooks}`),
    [`${REF}/5.scripts.md`]: page("Scripts", "The zero-dependency plugin scripts and their commands.", "i-lucide-file-code", `${NOTICE("plugin/scripts")}\n\nThe scripts folder path is in the session context; most are also \`agent-kit\` commands.\n\n${scripts}`),
    [`${REF}/6.changelog.md`]: page("Changelog", "What changed in every version.", "i-lucide-history", `${NOTICE("CHANGELOG.md")}\n\n${changelog}`),
  }
}

/** Leading `//` comment paragraph of a script (after the shebang and @-tags). */
function headerSummary(text) {
  const lines = []
  for (const line of text.split("\n").slice(text.startsWith("#!") ? 1 : 0)) {
    const m = line.match(/^\/\/ ?(.*)$/)
    if (!m) break
    if (!m[1].trim()) break
    if (m[1].startsWith("@") || /^\s{2,}node /.test(m[1])) continue
    lines.push(m[1].trim())
  }
  return lines.join(" ")
}

export function readSource(root = ROOT) {
  const help = readFileSync(join(root, "cli/lib/help.mjs"), "utf8").match(/export const HELP = `([\s\S]*?)`/)[1]
  const skillDirs = (base, origin) =>
    existsSync(join(root, base))
      ? readdirSync(join(root, base))
          .sort()
          .map((name) => {
            const { data } = parseFrontmatter(readFileSync(join(root, base, name, "SKILL.md"), "utf8"))
            const files = []
            for (const sub of ["references", "templates"])
              if (existsSync(join(root, base, name, sub))) for (const f of readdirSync(join(root, base, name, sub)).sort()) files.push(`${sub}/${f}`)
            return { name, description: data.description, origin, files }
          })
      : []
  const hooksJson = JSON.parse(readFileSync(join(root, "plugin/hooks/hooks.json"), "utf8")).hooks
  const hooks = Object.entries(hooksJson).flatMap(([event, groups]) =>
    groups.flatMap((g) =>
      g.hooks.map((h) => {
        const script = h.command.match(/scripts\/([\w.-]+\.mjs)/)?.[1] ?? h.command
        const file = join(root, "plugin/scripts", script)
        return { event, matcher: g.matcher ?? "", script, summary: existsSync(file) ? headerSummary(readFileSync(file, "utf8")) : "" }
      }),
    ),
  )
  const scripts = readdirSync(join(root, "plugin/scripts"))
    .filter((f) => f.endsWith(".mjs") && !f.endsWith(".test.mjs"))
    .sort()
    .map((f) => {
      const text = readFileSync(join(root, "plugin/scripts", f), "utf8")
      const usage = [...text.matchAll(/^\/\/\s{2,}(node \S+\.mjs.*)$/gm)].map((m) => m[1].trimEnd())
      return { name: f.replace(/\.mjs$/, ""), summary: headerSummary(text), usage }
    })
  return { help, questions: QUESTIONS, skills: [...skillDirs("plugin/skills", "plugin"), ...skillDirs("templates/skills", "template")], hooks, scripts, changelog: readFileSync(join(root, "CHANGELOG.md"), "utf8") }
}

export function syncDocs(root = ROOT, src = readSource(root)) {
  const written = []
  for (const [rel, text] of Object.entries(generatedPages(src))) {
    const path = join(root, rel)
    if (existsSync(path) && readFileSync(path, "utf8") === text) continue
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, text)
    written.push(rel)
  }
  return written
}

const walk = (dir) =>
  existsSync(dir)
    ? readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)).map((x) => `${f}/${x}`) : /\.(md|ya?ml)$/.test(f) ? [f] : []))
    : []

/** The source hash a translation records: `sourceHash:` in Markdown frontmatter, `# sourceHash:` in YAML. */
const recordedHash = (text) => text.match(/^#?\s*sourceHash:\s*([0-9a-f]+)/m)?.[1] ?? null

export function checkDocs(root = ROOT, src = readSource(root)) {
  const enDir = join(root, CONTENT, "en")
  const esDir = join(root, CONTENT, "es")
  const en = walk(enDir).sort()
  const es = walk(esDir).sort()
  const generated = Object.entries(generatedPages(src))
    .filter(([rel, text]) => !existsSync(join(root, rel)) || readFileSync(join(root, rel), "utf8") !== text)
    .map(([rel]) => rel)
  const missing = en.filter((f) => !es.includes(f)).map((f) => `${CONTENT}/es/${f}`)
  const orphans = es.filter((f) => !en.includes(f)).map((f) => `${CONTENT}/es/${f}`)
  const stale = en
    .filter((f) => es.includes(f) && recordedHash(readFileSync(join(esDir, f), "utf8")) !== pageHash(readFileSync(join(enDir, f), "utf8")))
    .map((f) => `${CONTENT}/es/${f}`)
  const prose = en.filter((f) => !f.startsWith("4.reference/")).map((f) => readFileSync(join(enDir, f), "utf8")).join("\n")
  const undocumented = parseHelp(src.help)
    .map((c) => c.cmd)
    .filter((cmd) => !new RegExp(`agent-kit ${cmd}\\b`).test(prose))
  return { missing, stale, orphans, generated, undocumented, ok: !missing.length && !stale.length && !orphans.length && !generated.length && !undocumented.length }
}

/** Record the current English hash in Spanish pages (after translating them). `all` = every Spanish page. */
export function stamp(root = ROOT, paths) {
  const enDir = join(root, CONTENT, "en")
  const esDir = join(root, CONTENT, "es")
  const targets = paths.includes("all") ? walk(esDir).filter((f) => existsSync(join(enDir, f))) : paths.map((p) => p.replace(/^.*?content\/es\//, "").replace(/^es\//, ""))
  const done = []
  for (const f of targets) {
    const hash = pageHash(readFileSync(join(enDir, f), "utf8"))
    const path = join(esDir, f)
    let text = readFileSync(path, "utf8")
    if (/\.ya?ml$/.test(f)) text = `# sourceHash: ${hash}\n${text.replace(/^# sourceHash:.*\n/m, "")}`
    else if (text.startsWith("---\n")) {
      const end = text.indexOf("\n---", 4)
      const fm = text.slice(4, end).split("\n").filter((l) => !l.startsWith("sourceHash:"))
      text = `---\n${[...fm, `sourceHash: ${hash}`].join("\n")}${text.slice(end)}`
    } else text = `---\nsourceHash: ${hash}\n---\n\n${text}`
    writeFileSync(path, text)
    done.push(`${CONTENT}/es/${f}`)
  }
  return done
}

function main([cmd, ...rest]) {
  if (cmd === "sync") {
    const w = syncDocs()
    console.log(w.length ? w.map((f) => `wrote ${f}`).join("\n") : "reference pages up to date")
    const r = checkDocs()
    if (r.stale.length) console.log(`\nTranslations to update (then stamp them):\n${r.stale.map((f) => `  ${f}`).join("\n")}`)
    return 0
  }
  if (cmd === "check") {
    const r = checkDocs()
    const show = (label, list) => list.length && console.log(`${label}:\n${list.map((f) => `  ${f}`).join("\n")}`)
    show("Generated pages out of date (run sync)", r.generated)
    show("Missing translations", r.missing)
    show("Stale translations (English changed; translate, then stamp)", r.stale)
    show("Spanish pages without an English page", r.orphans)
    show("CLI commands not explained outside the reference", r.undocumented)
    console.log(r.ok ? "✓ docs complete and current in every locale" : "✗ docs incomplete")
    return r.ok ? 0 : 1
  }
  if (cmd === "stamp") {
    if (!rest.length) return console.error("usage: docs.mjs stamp <site/content/es/…> | all"), 2
    for (const f of stamp(ROOT, rest)) console.log(`stamped ${relative(ROOT, join(ROOT, f))}`)
    return 0
  }
  console.log("usage: docs.mjs sync | check | stamp <site/content/es/…> | all")
  return cmd ? 2 : 0
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exit(main(process.argv.slice(2)))
