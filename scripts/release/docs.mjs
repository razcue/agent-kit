#!/usr/bin/env node
// @name: docs
// @summary: Website docs freshness: writes the generated reference pages (CLI, configuration, skills, hooks, scripts, changelog) from the kit's source, and checks every English page has a Spanish translation that is current (source hash) and every CLI command is explained.
// @usage: node scripts/release/docs.mjs sync | check | stamp <site/content/es/… | all>
// @tags: [release, site, docs, i18n]
// @test: docs.test.mjs
import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import { QUESTIONS } from "../../cli/lib/init.mjs"
import { parseFrontmatter } from "../../plugin/scripts/knowledge.mjs"

const ROOT = fileURLToPath(new URL("../../", import.meta.url))
export const CONTENT = "site/content"
export const LOCALES = ["en", "es"]
const REF = `${CONTENT}/en/4.reference`
const NOTICE = (source) => `<!-- Generated by scripts/release/docs.mjs from ${source} — edit the source, then run \`node scripts/release/docs.mjs sync\`. -->`

/** Hash of an English page: line endings and trailing spaces don't count. */
export function pageHash(text) {
  const norm = text.replace(/\r\n/g, "\n").split("\n").map((l) => l.trimEnd()).join("\n").trimEnd()
  return createHash("sha1").update(norm).digest("hex").slice(0, 12)
}

/** CLI help → commands: `  agent-kit <cmd> <args>   <summary>` plus deeper-indented detail lines. */
export function parseHelp(help) {
  const cmds = []
  for (const line of help.split("\n")) {
    const m = line.match(/^ {2}(agent-kit (\S+).*?)\s{2,}(\S.*)$/)
    if (m) cmds.push({ cmd: m[2], usage: m[1].trim(), summary: m[3].trim(), details: [] })
    else if (/^ {4,}\S/.test(line) && cmds.length) cmds[cmds.length - 1].details.push(line.trim())
  }
  return cmds
}

const cap = (s) => s.replace(/^./, (c) => c.toUpperCase())
const page = (title, description, icon, body) => `---\ntitle: ${title}\ndescription: ${description}\nnavigation:\n  icon: ${icon}\n---\n\n${body.trim()}\n`

