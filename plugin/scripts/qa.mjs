/** Regenerate checklist.md + checklist.html (or, with check, only report whether they are stale). */
export function syncQa(project, { check = false } = {}) {
  const cfg = qaConfig(project)
  if (!cfg.checklist) return { written: [], outOfSync: false, disabled: true }
  const seed = join(project, cfg.testDataDir, "seed.sql")
  const fixturesFile = cfg.testData && existsSync(seed) ? `${cfg.testDataDir}/seed.sql` : null
  const fixtures = fixturesFile ? parseFixtures(readFileSync(seed, "utf8")) : []
  const items = checklistItems(livingSpecs(project), fixtures)
  const files = { [`${QA_DIR}/checklist.md`]: renderChecklist(items, { fixturesFile }), [`${QA_DIR}/checklist.html`]: renderHtml(items, { name: readProject(project)?.name }) }
  const stale = Object.entries(files).filter(([rel, text]) => !existsSync(join(project, rel)) || readFileSync(join(project, rel), "utf8") !== text)
  if (check) return { written: [], outOfSync: stale.length > 0, items, fixtures }
  mkdirSync(join(project, QA_DIR), { recursive: true })
  for (const [rel, text] of stale) writeFileSync(join(project, rel), text)
  return { written: stale.map(([rel]) => rel), outOfSync: false, items, fixtures }
}

/** What preflight warns about: stale checklist, fixtures naming unknown scenarios, migrations without seed/purge changes. */
export function qaPreflight(project, status) {
  const cfg = qaConfig(project)
  const out = { outOfSync: false, unknown: [], migrationsWithoutSeed: [] }
  if (!cfg.checklist && !cfg.testData) return out
  const r = syncQa(project, { check: true })
  out.outOfSync = Boolean(cfg.checklist && r.outOfSync)
  if (!cfg.testData) return out
  const seed = join(project, cfg.testDataDir, "seed.sql")
  const fixtures = existsSync(seed) ? parseFixtures(readFileSync(seed, "utf8")) : []
  out.unknown = fixtureGaps(checklistItems(livingSpecs(project), fixtures), fixtures).unknown
  const files = [...status.keys()]
  const dataTouched = files.some((f) => f.endsWith(`${cfg.testDataDir}/seed.sql`) || f.endsWith(`${cfg.testDataDir}/purge.sql`))
  if (!dataTouched) out.migrationsWithoutSeed = files.filter((f) => /(^|\/)migrations\/[^/]+\.sql$/.test(f) && status.get(f) !== "D")
  return out
}

const readRuns = (project) => {
  const dir = join(project, QA_DIR, "runs")
  return existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")).map((name) => ({ name, text: readFileSync(join(dir, name), "utf8") })) : []
}

export function main(argv) {
  const [cmd] = argv
  const project = findProjectDir() ?? process.cwd()
  const cfg = qaConfig(project)
  if (cmd === "sync") {
    if (!cfg.checklist) return console.log("QA checklist is off (agent-kit.json qa.checklist) — re-run `agent-kit init` to turn it on."), 0
    const r = syncQa(project, { check: argv.includes("--check") })
    if (argv.includes("--check")) return console.log(r.outOfSync ? "✗ work/qa/checklist is out of date — run `qa.mjs sync`" : "✓ checklist up to date"), r.outOfSync ? 1 : 0
    console.log(r.written.length ? r.written.map((f) => `wrote ${f}`).join("\n") : "checklist up to date")
    console.log(`${r.items.length} scenario(s)`)
    return 0
  }
  const { items, fixtures } = syncQa(project, { check: true })
  if (cmd === "run") {
    const env = argv.includes("--env") ? argv[argv.indexOf("--env") + 1] : ""
    console.log(`created ${startRun(project, items, undefined, { environment: env })} — fill Result (pass / fail / blocked / n/a) and Note per scenario`)
    return 0
  }
  if (cmd === "status") {
    const st = qaStatus(items, readRuns(project))
    const counts = {}
    for (const s of st) counts[s.state] = (counts[s.state] ?? 0) + 1
    for (const s of st) if (s.state !== "pass") console.log(`${s.state.padEnd(9)} ${s.id}${s.run ? ` (${s.run}${s.note ? `: ${s.note}` : ""})` : ""}`)
    console.log(`${st.length} scenario(s): ${Object.entries(counts).map(([k, n]) => `${k} ${n}`).join(", ") || "none"}`)
    return 0
  }
  if (cmd === "gaps") {
    if (!cfg.testData) return console.log("Test data is off (agent-kit.json qa.testData)."), 0
    const g = fixtureGaps(items, fixtures)
    for (const u of g.unknown) console.log(`✗ seed.sql:${u.line} @fixture names unknown scenario ${u.id}`)
    console.log(g.withoutFixture.length ? `Without a fixture (fine when a scenario needs no data): ${g.withoutFixture.join(", ")}` : "Every scenario has a fixture.")
    return g.unknown.length ? 1 : 0
  }
  console.log("usage: qa.mjs sync [--check] | run [--env dev] | status | gaps")
  return cmd ? 2 : 0
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) process.exit(main(process.argv.slice(2)))
