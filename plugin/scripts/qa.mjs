#!/usr/bin/env node
// QA dimension: a checklist generated from the living specs (one item per
// scenario), dated QA runs that record results, and the map from scenarios to
// the test-data fixtures (`-- @fixture <ids…> @tag` in seed.sql).
//
//   node qa.mjs sync [--check]   regenerate work/qa/checklist.md + checklist.html (--check: exit 1 if stale)
//   node qa.mjs run              start work/qa/runs/<today>.md with every scenario unticked
//   node qa.mjs status           latest result per scenario (pass / fail / blocked / n/a / re-check / never run)
//   node qa.mjs gaps             scenarios without a fixture; fixtures naming unknown scenarios (exit 1)
import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { basename, join } from "node:path"
import { pathToFileURL } from "node:url"
import { findProjectDir, readProject } from "./config.mjs"
import { livingSpecs, parseSpec } from "./specs.mjs"

export const RESULTS = ["pass", "fail", "blocked", "n/a"]
export const QA_DIR = "work/qa"
export const DEFAULT_QA = { checklist: true, testData: false, testPrefix: "TEST_", testDataDir: "supabase/test-data" }

/** The project's QA settings; a project set up before QA existed (no `qa` key) has it off until `upgrade` asks. */
export const qaConfig = (project) => {
  const qa = readProject(project)?.qa
  return qa ? { ...DEFAULT_QA, ...qa } : { ...DEFAULT_QA, checklist: false, testData: false }
}

/** Short hash of a scenario (and its requirement sentence), whitespace-insensitive. */
export function scenarioHash(text) {
  return createHash("sha1").update(text.replace(/\s+/g, " ").trim()).digest("hex").slice(0, 8)
}

/** `-- @fixture cap.R1.S1 cap.R1.S2 @tag` lines of a seed file. */
export function parseFixtures(sql) {
  const out = []
  sql.split("\n").forEach((line, i) => {
    const m = line.match(/^\s*--\s*@fixture\s+(.+)$/)
    if (!m) return
    const ids = m[1].match(/[a-z][a-z0-9-]*\.R\d+\.S\d+/g) ?? []
    const tag = m[1].match(/@(\w+)/)?.[1] ?? null
    if (ids.length) out.push({ ids, tag, line: i + 1 })
  })
  return out
}

/** One item per living-spec scenario, in capability → requirement → scenario order. */
export function checklistItems(living, fixtures = []) {
  const items = []
  for (const { cap, text } of living)
    for (const req of parseSpec(text).requirements)
      for (const s of req.scenarios.filter((x) => x.req)) {
        const steps = s.lines.slice(1).map((l) => l.trim()).filter(Boolean).map((l) => l.replace(/^[-*]\s+/, ""))
        items.push({
          id: s.id,
          cap,
          reqId: req.id,
          reqName: req.name,
          sentence: req.sentence,
          name: s.name,
          tag: s.tag,
          steps,
          hash: scenarioHash(`${req.sentence}\n${s.text}`),
          fixtures: fixtures.filter((f) => f.ids.includes(s.id)).map((f) => ({ line: f.line, tag: f.tag })),
        })
      }
  return items
}

export function fixtureGaps(items, fixtures) {
  const known = new Set(items.map((i) => i.id))
  return {
    withoutFixture: items.filter((i) => !i.fixtures.length).map((i) => i.id),
    unknown: fixtures.flatMap((f) => f.ids.filter((id) => !known.has(id)).map((id) => ({ id, line: f.line }))),
  }
}

const groupBy = (items, key) => {
  const m = new Map()
  for (const i of items) (m.get(i[key]) ?? m.set(i[key], []).get(i[key])).push(i)
  return m
}

export function renderChecklist(items, { fixturesFile = null } = {}) {
  const caps = groupBy(items, "cap")
  const out = [
    "# QA checklist",
    "",
    "<!-- generated by `qa.mjs sync` from work/specs/ — do not edit. Record results in a run: `qa.mjs run` (work/qa/runs/) or checklist.html. -->",
    "",
    `${items.length} scenario(s) in ${caps.size} capability(ies).${fixturesFile ? ` Test data: \`${fixturesFile}\` (fixtures tagged \`-- @fixture <id> @tag\`).` : ""}`,
  ]
  if (!items.length) out.push("", "_No living specs yet — the checklist grows as changes are merged into work/specs/._")
  const file = fixturesFile ? basename(fixturesFile) : null
  for (const [cap, list] of caps) {
    out.push("", `## ${cap}`)
    for (const [, reqItems] of groupBy(list, "reqId")) {
      const r = reqItems[0]
      out.push("", `### ${r.reqId} — ${r.reqName}`, r.sentence, "")
      for (const i of reqItems) {
        const data = file ? ` · data: ${i.fixtures.length ? i.fixtures.map((f) => `${file}:${f.line}`).join(", ") : "no fixture"}` : ""
        out.push(`- [ ] **${i.id}** — ${i.name} \`@${i.tag}\`${data}`, ...i.steps.map((s) => `  - ${s}`))
      }
    }
  }
  return `${out.join("\n")}\n`
}

/** A QA run file. Self-contained (no outer references): checklist.html embeds it to export the same format. */
export function renderRun(items, date, results = {}, meta = {}) {
  const cell = (v) => String(v ?? "").replace(/\|/g, "/").replace(/\s+/g, " ").trim()
  const out = ["---", `date: ${date}`, `environment: ${cell(meta.environment)}`, `tester: ${cell(meta.tester)}`, "---", "", `# QA run ${date}`, "", "Result: pass · fail · blocked · n/a (empty = not run). The hash is the scenario text at run time."]
  let cap = null
  for (const i of items) {
    if (i.cap !== cap) {
      cap = i.cap
      out.push("", `## ${cap}`, "", "| Scenario | Hash | Result | Note |", "|---|---|---|---|")
    }
    const r = results[i.id] ?? {}
    out.push(`| ${i.id} | ${i.hash} | ${cell(r.result)} | ${cell(r.note)} |`)
  }
  return `${out.join("\n")}\n`
}

export function parseRun(text) {
  const rows = []
  for (const m of text.matchAll(/^\|\s*([a-z][a-z0-9-]*\.R\d+\.S\d+)\s*\|\s*([0-9a-f]*)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|\s*$/gm))
    rows.push({ id: m[1], hash: m[2], result: m[3].toLowerCase(), note: m[4] })
  return { rows }
}

/** Latest recorded result per item across runs (sorted by file name = date). */
export function qaStatus(items, runs) {
  const latest = new Map()
  for (const run of [...runs].sort((a, b) => a.name.localeCompare(b.name, "en", { numeric: true })))
    for (const r of parseRun(run.text).rows) if (RESULTS.includes(r.result)) latest.set(r.id, { ...r, run: run.name })
  return items.map((i) => {
    const l = latest.get(i.id)
    if (!l) return { id: i.id, state: "never run", run: null, note: "" }
    return { id: i.id, state: l.hash && l.hash !== i.hash ? "re-check" : l.result, run: l.run, note: l.note }
  })
}

export function startRun(project, items, date = new Date().toISOString().slice(0, 10), meta = {}) {
  const dir = join(project, QA_DIR, "runs")
  mkdirSync(dir, { recursive: true })
  let name = `${date}.md`
  for (let n = 2; existsSync(join(dir, name)); n++) name = `${date}-${n}.md`
  writeFileSync(join(dir, name), renderRun(items, date, {}, meta))
  return `${QA_DIR}/runs/${name}`
}

const escapeHtml = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c])

