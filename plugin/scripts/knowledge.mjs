#!/usr/bin/env node
// Knowledge base: one concept per Markdown file with frontmatter, grouped in
// scopes, linked with [[name]]. This script does the deterministic work (index,
// search, validation) so agents spend tokens only on the entries they open.
//
//   node knowledge.mjs paths
//   node knowledge.mjs find <terms...> [--body]
//   node knowledge.mjs related <name>       the entry, what it links to, what links to it
//   node knowledge.mjs index [--global]
//   node knowledge.mjs check [--global]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { basename, join, relative } from "node:path"
import { pathToFileURL } from "node:url"
import {
  ENTRY_STATUS,
  ENTRY_TYPES,
  GLOBAL_SCOPES,
  KNOWLEDGE_DIR,
  PROJECT_SCOPES,
  findProjectDir,
  globalKnowledge,
} from "./config.mjs"

const SKIP = new Set(["index.md", "README.md", "log.md"])

export function parseFrontmatter(text) {
  if (!text.startsWith("---\n")) return { data: {}, body: text }
  const end = text.indexOf("\n---", 4)
  if (end === -1) return { data: {}, body: text }
  const data = {}
  for (const line of text.slice(4, end).split("\n")) {
    const m = line.match(/^([\w-]+):\s*(.*)$/)
    if (!m) continue
    let value = m[2].trim()
    if (value.startsWith("[")) value = value.replace(/\]\s+#.*$/, "]")
    if (value.startsWith("[") && value.endsWith("]")) {
      value = value
        .slice(1, -1)
        .split(",")
        .map((v) => v.trim().replace(/^["']|["']$/g, ""))
        .filter(Boolean)
    } else if (/^["']/.test(value)) {
      value = value.replace(/^(["'])(.*)\1.*$/, "$2")
    } else {
      value = value.replace(/\s+#.*$/, "") // YAML: " #" starts a comment
    }
    data[m[1]] = value
  }
  return { data, body: text.slice(end + 4).replace(/^\n/, "") }
}

/** Scope roots: [{ origin, scope, dir }] for the project and the global base. */
export function scopeRoots({ project = true, global = true } = {}) {
  const roots = []
  const projectDir = project ? findProjectDir() : null
  if (projectDir) {
    for (const scope of PROJECT_SCOPES)
      roots.push({ origin: "project", scope, dir: join(projectDir, KNOWLEDGE_DIR, scope) })
  }
  const g = global ? globalKnowledge() : null
  if (g) {
    for (const scope of GLOBAL_SCOPES)
      roots.push({ origin: "global", scope, dir: join(g.dir, scope) })
  }
  return roots
}

export function collect(opts) {
  const entries = []
  for (const root of scopeRoots(opts)) {
    if (!existsSync(root.dir)) continue
    for (const file of readdirSync(root.dir).sort()) {
      if (!file.endsWith(".md") || SKIP.has(file)) continue
      const path = join(root.dir, file)
      const text = readFileSync(path, "utf8")
      const { data, body } = parseFrontmatter(text)
      entries.push({
        name: data.name || basename(file, ".md"),
        title: data.title || "",
        summary: data.summary || "",
        type: data.type || "",
        status: data.status || "active",
        tags: Array.isArray(data.tags) ? data.tags : [],
        origin: root.origin,
        scope: root.scope,
        path,
        file,
        body,
      })
    }
  }
  return entries
}

function line(e) {
  const meta = [e.type, e.status !== "active" ? e.status : ""].filter(Boolean).join(", ")
  return `- [[${e.name}]] — ${e.summary}${meta ? ` _(${meta})_` : ""}`
}

/** Entries listed in an overview index.md: Map<"scope/name", summary>. */
export function parseIndex(text) {
  const entries = new Map()
  let scope = null
  for (const line of text.split("\n")) {
    const h = line.match(/^## (\S+) \(\d+\)$/)
    if (h) scope = h[1]
    const e = scope && line.match(/^- \[\[([^\]]+)\]\] — (.*?)(?: _\(.*\)_)?$/)
    if (e) entries.set(`${scope}/${e[1]}`, e[2])
  }
  return entries
}

/** OKF-style change log lines between two index snapshots. */
export function logLines(before, after) {
  const lines = []
  for (const [key, summary] of after)
    if (!before.has(key)) lines.push(`- added ${key} — ${summary}`)
    else if (before.get(key) !== summary) lines.push(`- changed ${key} — ${summary}`)
  for (const key of before.keys()) if (!after.has(key)) lines.push(`- removed ${key}`)
  return lines
}

/** Rewrites index.md in every scope folder plus one overview per base. */
export function writeIndexes(opts) {
  const entries = collect(opts)
  const written = []
  const byBase = new Map()
  for (const root of scopeRoots(opts)) {
    if (!existsSync(root.dir)) continue
    const own = entries.filter((e) => e.origin === root.origin && e.scope === root.scope)
    const text = [
      `# ${root.scope}`,
      "",
      "<!-- generated by `knowledge.mjs index` — do not edit -->",
      "",
      ...(own.length ? own.map(line) : ["_(empty)_"]),
      "",
    ].join("\n")
    writeFileSync(join(root.dir, "index.md"), text)
    written.push(join(root.dir, "index.md"))
    const base = join(root.dir, "..")
    if (!byBase.has(base)) byBase.set(base, [])
    byBase.get(base).push({ scope: root.scope, own })
  }
  for (const [base, scopes] of byBase) {
    const parts = ["# Knowledge index", "", "<!-- generated by `knowledge.mjs index` — do not edit -->", ""]
    for (const { scope, own } of scopes) {
      if (scope === "local") continue
      parts.push(`## ${scope} (${own.length})`, "", ...(own.length ? own.map(line) : ["_(empty)_"]), "")
    }
    const indexPath = join(base, "index.md")
    const before = existsSync(indexPath) ? parseIndex(readFileSync(indexPath, "utf8")) : new Map()
    const next = parts.join("\n")
    writeFileSync(indexPath, next)
    written.push(indexPath)
    // OKF log.md: what changed in the knowledge, newest first, one dated block per run.
    const changes = logLines(before, parseIndex(next))
    if (changes.length) {
      const logPath = join(base, "log.md")
      const header = "# Knowledge log\n\n<!-- appended by `knowledge.mjs index` -->\n"
      const old = existsSync(logPath) ? readFileSync(logPath, "utf8").replace(header, "") : ""
      writeFileSync(logPath, `${header}\n## ${new Date().toISOString().slice(0, 10)}\n${changes.join("\n")}\n${old.replace(/^\n*/, "\n")}`.replace(/\n+$/, "\n"))
      written.push(logPath)
    }
  }
  return written
}

export function find(terms, { body = false } = {}) {
  const words = terms.map((t) => t.toLowerCase()).filter(Boolean)
  const scored = []
  for (const e of collect()) {
    const head = `${e.name} ${e.title} ${e.tags.join(" ")}`.toLowerCase()
    const summary = e.summary.toLowerCase()
    const text = body ? e.body.toLowerCase() : ""
    let score = 0
    for (const w of words) {
      if (head.includes(w)) score += 3
      if (summary.includes(w)) score += 2
      if (text.includes(w)) score += 1
    }
    if (score > 0) scored.push({ e, score })
  }
  return scored.sort((a, b) => b.score - a.score).slice(0, 20)
}

const linksOf = (body) =>
  [...body.replace(/```[\s\S]*?```/g, "").replace(/`[^`\n]*`/g, "").matchAll(/\[\[([^\]|]+)(?:\|[^\]]*)?\]\]/g)].map((m) => m[1].trim())

/** One hop around an entry: outgoing links and backlinks. */
export function related(name, entries = collect()) {
  const byName = new Map(entries.map((e) => [e.name, e]))
  const entry = byName.get(name)
  if (!entry) return null
  return {
    entry,
    links: [...new Set(linksOf(entry.body))].map((n) => byName.get(n) ?? { name: n, missing: true }),
    backlinks: entries.filter((e) => e.name !== name && linksOf(e.body).includes(name)),
  }
}

export function check(opts) {
  const entries = collect(opts)
  const errors = []
  const warnings = []
  const names = new Map()
  for (const e of entries) {
    const where = relative(process.cwd(), e.path)
    if (!e.summary) errors.push(`${where}: missing \`summary\``)
    else if (e.summary.length > 160) warnings.push(`${where}: summary is ${e.summary.length} chars — sessions show only 160; move detail to the body`)
    if (!ENTRY_TYPES.includes(e.type))
      errors.push(`${where}: \`type\` must be one of ${ENTRY_TYPES.join(", ")}`)
    if (!ENTRY_STATUS.includes(e.status))
      errors.push(`${where}: \`status\` must be one of ${ENTRY_STATUS.join(", ")}`)
    if (e.name !== basename(e.file, ".md")) errors.push(`${where}: \`name\` must match the file name`)
    const prev = names.get(e.name)
    if (prev) {
      const msg = `[[${e.name}]] defined twice: ${relative(process.cwd(), prev.path)} and ${where}`
      if (prev.origin !== e.origin) warnings.push(`${msg} (project overrides global)`)
      else errors.push(msg)
    }
    names.set(e.name, e)
  }
  for (const e of entries) {
    const prose = e.body.replace(/```[\s\S]*?```/g, "").replace(/`[^`\n]*`/g, "")
    for (const [, target] of prose.matchAll(/\[\[([^\]|]+)(?:\|[^\]]*)?\]\]/g)) {
      if (!names.has(target.trim()))
        warnings.push(`${relative(process.cwd(), e.path)}: link [[${target}]] has no entry yet`)
    }
  }
  return { errors, warnings, count: entries.length }
}

export function main(argv) {
  const [cmd, ...rest] = argv
  const flags = new Set(rest.filter((a) => a.startsWith("--")))
  const args = rest.filter((a) => !a.startsWith("--"))
  const scope = flags.has("--global") ? { project: false, global: true } : undefined

  if (cmd === "paths") {
    for (const r of scopeRoots()) console.log(`${r.origin}/${r.scope}\t${r.dir}`)
    const g = globalKnowledge()
    console.log(g ? `global writable: ${g.writable}` : "global: not found (run `agent-kit setup`)")
    return 0
  }
  if (cmd === "find") {
    if (!args.length) return usage()
    const hits = find(args, { body: flags.has("--body") })
    if (!hits.length) console.log("No match. Try other words or --body.")
    for (const { e } of hits) console.log(`${e.origin}/${e.scope}/${e.name} — ${e.summary}\n  ${e.path}`)
    return 0
  }
  if (cmd === "related") {
    const r = args[0] && related(args[0])
    if (!r) {
      console.log(args[0] ? `No entry named "${args[0]}". Try: find ${args[0]}` : "usage: related <name>")
      return 1
    }
    const one = (e) => (e.missing ? `- ${e.name} (no entry yet)` : `- ${e.origin}/${e.scope}/${e.name} — ${e.summary}\n  ${e.path}`)
    console.log(`${r.entry.origin}/${r.entry.scope}/${r.entry.name} — ${r.entry.summary}\n  ${r.entry.path}`)
    console.log(`\nLinks to:\n${r.links.map(one).join("\n") || "- none"}`)
    console.log(`\nLinked from:\n${r.backlinks.map(one).join("\n") || "- none"}`)
    return 0
  }
  if (cmd === "index") {
    for (const f of writeIndexes(scope)) console.log(`wrote ${relative(process.cwd(), f)}`)
    return 0
  }
  if (cmd === "check") {
    const { errors, warnings, count } = check(scope)
    for (const w of warnings) console.log(`warn  ${w}`)
    for (const e of errors) console.log(`error ${e}`)
    console.log(`${count} entries, ${errors.length} error(s), ${warnings.length} warning(s)`)
    return errors.length ? 1 : 0
  }
  return usage()
}

function usage() {
  console.log("usage: knowledge.mjs paths | find <terms...> [--body] | related <name> | index [--global] | check [--global]")
  return 2
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exit(main(process.argv.slice(2)))
}
